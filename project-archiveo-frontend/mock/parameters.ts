let _id = 0;
const uid = (p: string) => `${p}-${(++_id).toString().padStart(4, '0')}`;

function g(
  code: string,
  name: string,
  icon: string,
  color: string,
  order: number,
  items: Array<{ code: string; name: string; description?: string; color?: string; icon?: string }>
): ParameterGroup {
  return {
    id: uid('grp'),
    code,
    name,
    icon,
    color,
    order,
    items: items.map((it, i) => ({
      id: uid(code),
      code: it.code,
      name: it.name,
      description: it.description,
      color: it.color,
      icon: it.icon,
      order: i + 1,
      active: true,
      parentId: null,
    })),
  };
}

